package com.netaji.CrudOperation.mapper;

public class UserRequest {
    String name;
    long mobileNo;
    String email;
    String password;

    public String getName() {
        return name;
    }

    public long getMobileNo() {
        return mobileNo;
    }

    public String getEmail() {
        return email;
    }

    public String getPassword() {
        return password;
    }
}
